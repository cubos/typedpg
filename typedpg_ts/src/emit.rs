//! The generated module of a database.
//!
//! ```ts
//! import { createCopyIn, createSql } from "@cubos/typedpg";
//!
//! export interface Queries {
//!   "SELECT name FROM users WHERE id = $id": {
//!     params: { id: number };
//!     row: { name: string | null };
//!     value: string | null;
//!   };
//!   "SELECT nmae FROM users": { error: "column \"nmae\" does not exist" };
//! }
//!
//! export interface CopyTargets {
//!   "users (name, email)": { row: { name: string; email: string | null } };
//! }
//!
//! export const sql = createSql<Queries>({
//!   "SELECT name FROM users WHERE id = $id": "{\"sql\":[...],\"params\":[...],...}",
//! });
//! export const copyIn = createCopyIn<CopyTargets>({ ... });
//! ```
//!
//! A `.js` / `.mjs` / `.cjs` `out` is the same split in two: the values in
//! the JavaScript module, the interfaces in its declaration file. Entries are
//! sorted by text, so the output is deterministic and a new query is a local
//! diff.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use typedpg_core::config::MigrationsConfig;

use crate::config::{OutKind, declaration_path};
use crate::generate::{GenError, Generated};
use crate::typemap::{EnumNames, RUNTIME_NS, js_string};

/// A query's or COPY target's text and what was generated for it.
pub type Entry<'a> = (&'a str, &'a Result<Generated, GenError>);

/// The migrations a module embeds, and the runner's settings.
pub struct Embedded<'a> {
    /// `(name, up SQL, down SQL)`.
    pub migrations: &'a [(String, String, Option<String>)],
    pub runner: &'a MigrationsConfig,
}

/// A type `types` maps a PG type to, and what that type is read as, which
/// it must fit ([`crate::typemap::Codec::fits`]).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TypeCheck {
    /// The PG type, as written in the config.
    pub pg: String,
    /// The type imported for it.
    pub ts: String,
    pub fits: String,
}

pub struct Module<'a> {
    pub runtime: &'a str,
    /// `(module, type name)` the type mappings need.
    pub imports: &'a [(String, String)],
    pub checks: &'a [TypeCheck],
    /// The names the module gives the database's enums: it exports each of
    /// the user's, and any other its types name.
    pub enums: &'a EnumNames,
    pub queries: &'a [Entry<'a>],
    pub copies: &'a [Entry<'a>],
    pub migrations: Option<Embedded<'a>>,
}

/// The names the module declares: a type `types` maps to can't be one of
/// them, the module imports it.
pub const MODULE_BINDINGS: &[&str] = &[
    "createCopyIn",
    "createSql",
    "embedMigrations",
    RUNTIME_NS,
    "TypeMappingChecks",
    "Queries",
    "CopyTargets",
    "sql",
    "copyIn",
    "migrations",
];

const HEADER: &str = "// @generated by typedpg from the queries in this project's sources. Do \
                      not edit:\n// run `typedpg gen` after changing a query or a \
                      migration.\n/* eslint-disable */\n";

impl Module<'_> {
    /// The files of the module at `out`: `(path, contents)`.
    pub fn files(&self, out: &Path, kind: OutKind) -> Vec<(PathBuf, String)> {
        match kind {
            OutKind::TypeScript => vec![(out.to_path_buf(), self.typescript())],
            OutKind::EsModule | OutKind::CommonJs => {
                let declaration = declaration_path(out).expect("a JavaScript out");
                vec![
                    (
                        out.to_path_buf(),
                        self.javascript(kind == OutKind::CommonJs),
                    ),
                    (declaration, self.declaration()),
                ]
            }
        }
    }

    fn typescript(&self) -> String {
        let mut out = String::from(HEADER);
        let mut values = vec!["createCopyIn", "createSql"];
        if self.migrations.is_some() {
            values.push("embedMigrations");
        }
        let runtime = js_string(self.runtime);
        let _ = writeln!(out, "import {{ {} }} from {runtime};", values.join(", "));
        self.type_imports(&mut out);
        out.push('\n');
        self.enum_types(&mut out);
        self.type_checks(&mut out);
        self.interfaces(&mut out);
        out.push('\n');
        self.values(&mut out, "export const ", "<Queries>", "<CopyTargets>");
        out
    }

    fn javascript(&self, commonjs: bool) -> String {
        let mut out = String::from(HEADER);
        let mut values = vec!["createCopyIn", "createSql"];
        if self.migrations.is_some() {
            values.push("embedMigrations");
        }
        let runtime = js_string(self.runtime);
        if commonjs {
            let _ = writeln!(
                out,
                "\"use strict\";\nconst {{ {} }} = require({runtime});\n",
                values.join(", ")
            );
            self.values(&mut out, "exports.", "", "");
        } else {
            let _ = writeln!(out, "import {{ {} }} from {runtime};\n", values.join(", "));
            self.values(&mut out, "export const ", "", "");
        }
        out
    }

    fn declaration(&self) -> String {
        let mut out = String::from(HEADER);
        let _ = writeln!(
            out,
            "import type * as {RUNTIME_NS} from {};",
            js_string(self.runtime)
        );
        self.user_imports(&mut out);
        out.push('\n');
        self.enum_types(&mut out);
        self.type_checks(&mut out);
        self.interfaces(&mut out);
        let _ = writeln!(
            out,
            "\nexport declare const sql: {RUNTIME_NS}.Sql<Queries>;\n\
             export declare const copyIn: {RUNTIME_NS}.CopyIn<CopyTargets>;"
        );
        if self.migrations.is_some() {
            let _ = writeln!(
                out,
                "export declare const migrations: {RUNTIME_NS}.MigrationSet;"
            );
        }
        out
    }

    fn uses_runtime_types(&self) -> bool {
        let prefix = format!("{RUNTIME_NS}.");
        !self.checks.is_empty()
            || self
                .queries
                .iter()
                .chain(self.copies)
                .any(|(_, r)| r.as_ref().is_ok_and(|g| g.types.contains(&prefix)))
    }

    fn type_imports(&self, out: &mut String) {
        if self.uses_runtime_types() {
            let _ = writeln!(
                out,
                "import type * as {RUNTIME_NS} from {};",
                js_string(self.runtime)
            );
        }
        self.user_imports(out);
    }

    /// One `import type` per module, the names sorted (`imports` is).
    fn user_imports(&self, out: &mut String) {
        let mut i = 0;
        while i < self.imports.len() {
            let module = &self.imports[i].0;
            let names: Vec<&str> = self.imports[i..]
                .iter()
                .take_while(|(m, _)| m == module)
                .map(|(_, n)| n.as_str())
                .collect();
            i += names.len();
            let _ = writeln!(
                out,
                "import type {{ {} }} from {};",
                names.join(", "),
                js_string(module)
            );
        }
    }

    /// `export type Mood = "happy" | "sad";` for each enum.
    fn enum_types(&self, out: &mut String) {
        let types = self
            .queries
            .iter()
            .chain(self.copies)
            .filter_map(|(_, r)| r.as_ref().ok().map(|g| g.types.as_str()));
        let declarations = self.enums.declarations(types, true);
        if !declarations.is_empty() {
            out.push_str(&declarations);
            out.push('\n');
        }
    }

    /// A type that fails to compile where a type `types` maps to doesn't
    /// fit what its PG type is read as: the runtime would hand out values
    /// the type doesn't describe.
    fn type_checks(&self, out: &mut String) {
        if self.checks.is_empty() {
            return;
        }
        out.push_str(
            "// Each type in `types` must fit what its PostgreSQL type is read as.\n\
             export type TypeMappingChecks = [\n",
        );
        for c in self.checks {
            let _ = writeln!(
                out,
                "  {RUNTIME_NS}.Fits<{}, {}>, // {}",
                c.ts, c.fits, c.pg
            );
        }
        out.push_str("];\n\n");
    }

    fn interfaces(&self, out: &mut String) {
        for (name, entries) in [("Queries", self.queries), ("CopyTargets", self.copies)] {
            if name == "CopyTargets" {
                out.push('\n');
            }
            let _ = writeln!(out, "export interface {name} {{");
            for (text, result) in entries {
                let key = js_string(text);
                match result {
                    Ok(g) => {
                        if let Some(note) = &g.simplified {
                            out.push_str("  /**\n");
                            for line in note.replace("*/", "*\\/").lines() {
                                let sep = if line.is_empty() { "" } else { " " };
                                let _ = writeln!(out, "   *{sep}{line}");
                            }
                            out.push_str("   */\n");
                        }
                        let _ = writeln!(out, "  {key}: {};", self.enums.render(&g.types));
                    }
                    Err(e) => {
                        // The message's first line: the rest is the
                        // rendered snippet, which the CLI prints.
                        let first = e.message.lines().next().unwrap_or_default();
                        let _ = writeln!(out, "  {key}: {{ error: {} }};", js_string(first));
                    }
                }
            }
            out.push_str("}\n");
        }
    }

    fn values(&self, out: &mut String, export: &str, queries_ty: &str, copies_ty: &str) {
        for (name, create, ty, entries) in [
            ("sql", "createSql", queries_ty, self.queries),
            ("copyIn", "createCopyIn", copies_ty, self.copies),
        ] {
            let _ = writeln!(out, "{export}{name} = {create}{ty}({{");
            for (text, result) in entries {
                if let Ok(g) = result {
                    let _ = writeln!(out, "  {}: {},", js_string(text), js_string(&g.runtime));
                }
            }
            out.push_str("});\n");
        }
        if let Some(m) = &self.migrations {
            let _ = writeln!(out, "{export}migrations = embedMigrations([");
            for (name, sql, down) in m.migrations {
                let down = down.as_deref().map_or_else(|| "null".to_owned(), js_string);
                let _ = writeln!(out, "  [{}, {}, {down}],", js_string(name), js_string(sql));
            }
            let r = m.runner;
            let _ = writeln!(
                out,
                "], {{ table: {}, lockId: {}, useTransaction: {}, failOnDrift: {} }});",
                js_string(&r.table),
                js_lock_id(r.lock_id),
                r.use_transaction,
                r.fail_on_drift
            );
        }
    }
}

/// The advisory lock's id as JavaScript: a number, or a BigInt literal past
/// the integers a number holds exactly (2^53 - 1) — rounded, the npm runner
/// would take another lock than `typedpg migrate`, and the two would no
/// longer keep each other out.
fn js_lock_id(lock_id: i64) -> String {
    const MAX_SAFE_INTEGER: u64 = (1 << 53) - 1;
    if lock_id.unsigned_abs() > MAX_SAFE_INTEGER {
        format!("{lock_id}n")
    } else {
        lock_id.to_string()
    }
}

#[cfg(test)]
mod tests {
    #[test]
    fn a_lock_id_past_a_javascript_number_is_a_bigint() {
        use super::js_lock_id;
        assert_eq!(js_lock_id(713705), "713705");
        assert_eq!(js_lock_id(-713705), "-713705");
        assert_eq!(js_lock_id(9_007_199_254_740_991), "9007199254740991");
        assert_eq!(js_lock_id(9_007_199_254_740_993), "9007199254740993n");
        assert_eq!(js_lock_id(i64::MIN), "-9223372036854775808n");
    }

    use super::*;

    fn generated(types: &str) -> Result<Generated, GenError> {
        Ok(Generated {
            types: types.to_owned(),
            params: Vec::new(),
            row: Vec::new(),
            value: None,
            overrides: Vec::new(),
            runtime: "{\"sql\":[\"x\"]}".to_owned(),
            simplified: None,
        })
    }

    #[test]
    fn typescript_module() {
        let q = generated("{ params: {}; row: { r: typedpg.Range<number> } }");
        let e = Err(GenError {
            message: "column \"x\" does not exist\n  ╭────".into(),
            offset: Some(7),
        });
        let queries = [("SELECT r", &q), ("SELECT x", &e)];
        let imports = [
            ("./domains".to_owned(), "Point".to_owned()),
            ("./domains".to_owned(), "Prefs".to_owned()),
            ("pkg".to_owned(), "X".to_owned()),
        ];
        let m = Module {
            runtime: "@cubos/typedpg",
            imports: &imports,
            checks: &[],
            enums: &EnumNames::default(),
            queries: &queries,
            copies: &[],
            migrations: None,
        };
        let files = m.files(Path::new("/p/db.ts"), OutKind::TypeScript);
        assert_eq!(files.len(), 1);
        let ts = &files[0].1;
        assert!(ts.contains("import { createCopyIn, createSql } from \"@cubos/typedpg\";\nimport type * as typedpg from \"@cubos/typedpg\";\nimport type { Point, Prefs } from \"./domains\";\nimport type { X } from \"pkg\";"), "{ts}");
        assert!(
            ts.contains(r#"  "SELECT x": { error: "column \"x\" does not exist" };"#),
            "{ts}"
        );
        assert!(ts.contains("export const sql = createSql<Queries>({\n  \"SELECT r\": \"{\\\"sql\\\":[\\\"x\\\"]}\",\n});"), "{ts}");
        assert!(ts.contains("export interface CopyTargets {\n}"), "{ts}");
        assert!(
            ts.contains("export const copyIn = createCopyIn<CopyTargets>({\n});"),
            "{ts}"
        );
    }

    #[test]
    fn a_simplified_query_is_documented() {
        let q = Ok(Generated {
            simplified: Some(
                "Sent simplified by typedpg (not_in):\n\n```sql\nSELECT 1\n```".into(),
            ),
            ..generated("{ params: {}; row: {} }").unwrap()
        });
        let queries = [("SELECT a", &q)];
        let m = Module {
            runtime: "@cubos/typedpg",
            imports: &[],
            checks: &[],
            enums: &EnumNames::default(),
            queries: &queries,
            copies: &[],
            migrations: None,
        };
        let ts = &m.files(Path::new("/p/db.ts"), OutKind::TypeScript)[0].1;
        assert!(
            ts.contains(
                "  /**\n   * Sent simplified by typedpg (not_in):\n   *\n   * ```sql\n   * SELECT \
                 1\n   * ```\n   */\n  \"SELECT a\": { params: {}; row: {} };"
            ),
            "{ts}"
        );
    }

    #[test]
    fn javascript_modules_come_with_declarations() {
        let q = generated("{ params: {}; row: {} }");
        let queries = [("SELECT", &q)];
        let runner = MigrationsConfig::default();
        let migrations = [("0001_a".to_owned(), "CREATE TABLE a ();".to_owned(), None)];
        let m = Module {
            runtime: "@cubos/typedpg",
            imports: &[],
            checks: &[],
            enums: &EnumNames::default(),
            queries: &queries,
            copies: &[],
            migrations: Some(Embedded {
                migrations: &migrations,
                runner: &runner,
            }),
        };
        let files = m.files(Path::new("/p/db.cjs"), OutKind::CommonJs);
        assert_eq!(files[0].0, PathBuf::from("/p/db.cjs"));
        assert_eq!(files[1].0, PathBuf::from("/p/db.d.cts"));
        let (js, dts) = (&files[0].1, &files[1].1);
        assert!(
            js.contains(
                "const { createCopyIn, createSql, embedMigrations } = require(\"@cubos/typedpg\");"
            ),
            "{js}"
        );
        assert!(js.contains("exports.sql = createSql({"), "{js}");
        assert!(js.contains("exports.migrations = embedMigrations([\n  [\"0001_a\", \"CREATE TABLE a ();\", null],\n], { table: \"public._migrations\", lockId: 713705, useTransaction: true, failOnDrift: true });"), "{js}");
        assert!(!js.contains("interface"), "{js}");
        assert!(
            dts.contains("export declare const sql: typedpg.Sql<Queries>;"),
            "{dts}"
        );
        assert!(
            dts.contains("export declare const migrations: typedpg.MigrationSet;"),
            "{dts}"
        );

        let files = m.files(Path::new("/p/db.js"), OutKind::EsModule);
        assert_eq!(files[1].0, PathBuf::from("/p/db.d.ts"));
        assert!(files[0].1.contains("export const sql = createSql({"));
    }

    /// A lock id a JS number can't hold exactly is written as a bigint:
    /// rounded, it would be another lock than the Rust runner takes.
    #[test]
    fn a_large_lock_id_is_a_bigint() {
        let lock = |lock_id: i64| {
            let runner = MigrationsConfig {
                lock_id,
                ..MigrationsConfig::default()
            };
            let m = Module {
                runtime: "@cubos/typedpg",
                imports: &[],
                checks: &[],
                enums: &EnumNames::default(),
                queries: &[],
                copies: &[],
                migrations: Some(Embedded {
                    migrations: &[],
                    runner: &runner,
                }),
            };
            let ts = m.files(Path::new("/p/db.ts"), OutKind::TypeScript)[0]
                .1
                .clone();
            let at = ts.find("lockId: ").expect("the runner's settings") + "lockId: ".len();
            ts[at..].split(',').next().unwrap().to_owned()
        };
        assert_eq!(lock(9_007_199_254_740_991), "9007199254740991");
        assert_eq!(lock(-9_007_199_254_740_991), "-9007199254740991");
        assert_eq!(lock(9_007_199_254_740_993), "9007199254740993n");
        assert_eq!(lock(i64::MIN), "-9223372036854775808n");
    }

    /// Every name the module binds at its top level is an imported
    /// override or in `MODULE_BINDINGS`, in each form of the module; and
    /// each of `MODULE_BINDINGS` is bound by one.
    #[test]
    fn module_bindings_are_every_name_the_module_binds() {
        use crate::sqlmodule::top_level_bindings;
        use oxc_span::SourceType;

        // The user's enums, one named as the module's interface; an
        // extension's a query names, and one none does.
        let enum_ty =
            |schema: &str, name: &str, extension: Option<&str>| typedpg_analyzer::Type::Enum {
                schema: schema.into(),
                name: name.into(),
                labels: vec!["a".into()],
                extension: extension.map(str::to_owned),
            };
        let mark = |schema: &str, name: &str| {
            crate::typemap::enum_mark(&typedpg_core::QualifiedName::new(schema, name))
        };
        let enums = crate::typemap::Enums::from_types(
            vec![
                enum_ty("public", "mood", None),
                enum_ty("public", "queries", None),
                enum_ty("ext", "flag", Some("ext")),
                enum_ty("ext", "unused", Some("ext")),
            ],
            &Default::default(),
        )
        .names(MODULE_BINDINGS.iter().copied().chain(["Prefs"]));
        let q = generated(&format!(
            "{{ params: {{}}; row: {{ p: Prefs; r: typedpg.Range<number>; f: {} }} }}",
            mark("ext", "flag")
        ));
        let e = Err(GenError {
            message: "column \"x\" does not exist".into(),
            offset: None,
        });
        let c = generated(&format!(
            "{{ row: {{ p: Prefs; m: {} }} }}",
            mark("public", "mood")
        ));
        let queries = [("SELECT p, r", &q), ("SELECT x", &e)];
        let copies = [("t (p)", &c)];
        let imports = [("./domains".to_owned(), "Prefs".to_owned())];
        let checks = [TypeCheck {
            pg: "prefs".into(),
            ts: "Prefs".into(),
            fits: "unknown".into(),
        }];
        let runner = MigrationsConfig::default();
        let migrations = [("0001_a".to_owned(), "CREATE TABLE a ();".to_owned(), None)];
        let m = Module {
            runtime: "@cubos/typedpg",
            imports: &imports,
            checks: &checks,
            enums: &enums,
            queries: &queries,
            copies: &copies,
            migrations: Some(Embedded {
                migrations: &migrations,
                runner: &runner,
            }),
        };
        let ts = m.files(Path::new("/p/db.ts"), OutKind::TypeScript);
        let declared = "\nexport type ExtFlag = \"a\";\nexport type Mood = \"a\";\n\
                        export type PublicQueries = \"a\";\n\n";
        assert!(ts[0].1.contains(declared), "{}", ts[0].1);
        assert!(
            ts[0].1.contains("f: ExtFlag } };") && ts[0].1.contains("m: Mood } };"),
            "{}",
            ts[0].1
        );
        let own = ["Prefs", "ExtFlag", "Mood", "PublicQueries"];
        let esm = m.files(Path::new("/p/db.js"), OutKind::EsModule);
        let cjs = m.files(Path::new("/p/db.cjs"), OutKind::CommonJs);
        let forms = [
            ("ts", &ts[0].1, SourceType::ts()),
            ("esm", &esm[0].1, SourceType::mjs()),
            ("esm d.ts", &esm[1].1, SourceType::d_ts()),
            ("cjs", &cjs[0].1, SourceType::cjs()),
            ("cjs d.cts", &cjs[1].1, SourceType::d_ts()),
        ];
        let mut bound = std::collections::BTreeSet::new();
        for (form, text, ty) in forms {
            for name in top_level_bindings(text, ty) {
                if !own.contains(&name.as_str()) {
                    assert!(
                        MODULE_BINDINGS.contains(&name.as_str()),
                        "{form}: `{name}` is not in MODULE_BINDINGS\n{text}"
                    );
                    bound.insert(name);
                }
            }
        }
        let listed: std::collections::BTreeSet<String> =
            MODULE_BINDINGS.iter().map(|s| s.to_string()).collect();
        assert_eq!(bound, listed, "a name in MODULE_BINDINGS no module binds");
    }
}
