//! The module of a `.sql` file: an export per query.
//!
//! ```ts
//! import { createQuery } from "@cubos/typedpg";
//!
//! export interface UserByIdParams {
//!   id: number;
//! }
//!
//! export interface UserByIdRow {
//!   name: string | null;
//! }
//!
//! /** … the SQL … */
//! export const userById = createQuery<{ params: UserByIdParams; row: UserByIdRow; value: string | null }>(
//!   "SELECT name FROM users WHERE id = $id", "{\"sql\":[...],...}");
//! ```
//!
//! The same module is written in several forms: TypeScript (`emit: "ts"`),
//! JavaScript with its declaration file, the declarations alone
//! (`<name>.d.sql.ts`), the JavaScript a loader runs, and the TypeScript the
//! content mapper hands to tsc — with where each export's name is, to map
//! it to the `@name` in the file.
//!
//! A query with an error is exported too, as a `createBrokenQuery`: each
//! use of it fails to type-check with the error, and fails at runtime.
//! Its types are `any`, so that the error is the only one reported.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::config::{OutKind, TypeNames, declaration_path};
use crate::emit::TypeCheck;
use crate::generate::{GenError, Generated};
use crate::typemap::{RUNTIME_NS, js_string};

/// A query of the file and what was generated for it.
pub struct SqlQuery<'a> {
    pub name: &'a str,
    pub text: &'a str,
    pub result: &'a Result<Generated, GenError>,
    /// The checks of the `types` overrides its types use.
    pub checks: Vec<&'a TypeCheck>,
}

pub struct SqlModule<'a> {
    pub runtime: &'a str,
    /// The `.sql` file, relative to the module: the header names it.
    pub source: String,
    /// `(module, type name)` of every override the database maps; only those
    /// the queries use are imported.
    pub imports: &'a [(String, String)],
    pub queries: &'a [SqlQuery<'a>],
    pub type_names: &'a TypeNames,
}

/// The first line of a module `typedpg gen` writes for a `.sql` file, up to
/// the file's name (unlike a database module's, `from the queries in this
/// project's sources`).
pub const GENERATED_PREFIX: &str = "// @generated by typedpg from the SQL file ";
const GENERATED_SUFFIX: &str = ". Do not edit:";

/// The `.sql` file a generated module's first line names, relative to the
/// module; `None` for any other file.
pub fn generated_source(first_line: &str) -> Option<&str> {
    first_line
        .strip_prefix(GENERATED_PREFIX)?
        .strip_suffix(GENERATED_SUFFIX)
        .filter(|source| source.ends_with(".sql"))
}

/// The TypeScript of a module, and where each query's export name is in
/// it: `(byte offset, query index)`.
pub struct Mapped {
    pub text: String,
    pub exports: Vec<(usize, usize)>,
}

impl SqlModule<'_> {
    fn generated_header(&self) -> String {
        format!(
            "{GENERATED_PREFIX}{}{GENERATED_SUFFIX}\n// run `typedpg gen` after changing a query or a \
             migration.\n/* eslint-disable */\n",
            self.source
        )
    }

    /// The files `emit: "ts"` writes at `out`: `(path, contents)`.
    pub fn files(&self, out: &Path, kind: OutKind) -> Vec<(PathBuf, String)> {
        let header = self.generated_header();
        match kind {
            OutKind::TypeScript => {
                vec![(out.to_path_buf(), header + &self.typescript().text)]
            }
            OutKind::EsModule | OutKind::CommonJs => {
                let declaration = declaration_path(out).expect("a JavaScript out");
                vec![
                    (
                        out.to_path_buf(),
                        header.clone() + &self.javascript(kind == OutKind::CommonJs),
                    ),
                    (declaration, header + &self.declaration()),
                ]
            }
        }
    }

    /// `<name>.d.sql.ts`, for `emit: "dts"`.
    pub fn declaration_file(&self) -> String {
        self.generated_header() + &self.declaration()
    }

    /// The ES module a loader or bundler plugin runs for the file.
    pub fn loader_module(&self) -> String {
        format!("// compiled by typedpg from {}\n", self.source) + &self.javascript(false)
    }

    /// The TypeScript the content mapper gives tsc for the file.
    pub fn mapped(&self) -> Mapped {
        let header = format!("// compiled by typedpg from {}\n", self.source);
        let mut m = self.typescript();
        m.text.insert_str(0, &header);
        for e in &mut m.exports {
            e.0 += header.len();
        }
        m
    }

    fn values_import(&self) -> String {
        let mut values = Vec::new();
        if self.queries.iter().any(|q| q.result.is_err()) {
            values.push("createBrokenQuery");
        }
        if self.queries.iter().any(|q| q.result.is_ok()) {
            values.push("createQuery");
        }
        values.join(", ")
    }

    /// The overrides the queries use: `(module, name)`, sorted by module.
    fn used_imports(&self) -> Vec<&(String, String)> {
        self.imports
            .iter()
            .filter(|(_, name)| {
                self.queries
                    .iter()
                    .any(|q| q.result.as_ref().is_ok_and(|g| g.overrides.contains(name)))
            })
            .collect()
    }

    /// One `import type` per module.
    fn user_imports(&self, out: &mut String) {
        let used = self.used_imports();
        let mut i = 0;
        while i < used.len() {
            let module = &used[i].0;
            let names: Vec<&str> = used[i..]
                .iter()
                .take_while(|(m, _)| m == module)
                .map(|(_, n)| n.as_str())
                .collect();
            i += names.len();
            let _ = writeln!(
                out,
                "import type {{ {} }} from {};",
                names.join(", "),
                js_string(module)
            );
        }
    }

    fn uses_runtime_types(&self) -> bool {
        let prefix = format!("{RUNTIME_NS}.");
        self.queries.iter().any(|q| {
            !q.checks.is_empty() || q.result.as_ref().is_ok_and(|g| g.types.contains(&prefix))
        })
    }

    fn typescript(&self) -> Mapped {
        let mut out = String::new();
        let values = self.values_import();
        let runtime = js_string(self.runtime);
        if !values.is_empty() {
            let _ = writeln!(out, "import {{ {values} }} from {runtime};");
        }
        if self.uses_runtime_types() {
            let _ = writeln!(out, "import type * as {RUNTIME_NS} from {runtime};");
        }
        self.user_imports(&mut out);
        let mut exports = Vec::new();
        for (i, q) in self.queries.iter().enumerate() {
            out.push('\n');
            self.types(&mut out, q);
            doc(&mut out, q.text);
            out.push_str("export const ");
            exports.push((out.len(), i));
            match q.result {
                Ok(g) => {
                    let _ = writeln!(
                        out,
                        "{} = createQuery<{}{}>(\n  {},\n  {},\n);",
                        q.name,
                        self.query_types(q.name, g),
                        checks(&q.checks),
                        js_string(q.text),
                        js_string(&g.runtime)
                    );
                }
                Err(e) => {
                    let _ = writeln!(
                        out,
                        "{} = createBrokenQuery({}, {});",
                        q.name,
                        js_string(q.text),
                        js_string(first_line(e))
                    );
                }
            }
        }
        Mapped { text: out, exports }
    }

    fn javascript(&self, commonjs: bool) -> String {
        let mut out = String::new();
        let values = self.values_import();
        let runtime = js_string(self.runtime);
        let export = if commonjs {
            out.push_str("\"use strict\";\n");
            if !values.is_empty() {
                let _ = writeln!(out, "const {{ {values} }} = require({runtime});");
            }
            "exports."
        } else {
            if !values.is_empty() {
                let _ = writeln!(out, "import {{ {values} }} from {runtime};");
            }
            "export const "
        };
        for q in self.queries {
            out.push('\n');
            match q.result {
                Ok(g) => {
                    let _ = writeln!(
                        out,
                        "{export}{} = createQuery(\n  {},\n  {},\n);",
                        q.name,
                        js_string(q.text),
                        js_string(&g.runtime)
                    );
                }
                Err(e) => {
                    let _ = writeln!(
                        out,
                        "{export}{} = createBrokenQuery({}, {});",
                        q.name,
                        js_string(q.text),
                        js_string(first_line(e))
                    );
                }
            }
        }
        out
    }

    fn declaration(&self) -> String {
        let mut out = String::new();
        let _ = writeln!(
            out,
            "import type * as {RUNTIME_NS} from {};",
            js_string(self.runtime)
        );
        self.user_imports(&mut out);
        for q in self.queries {
            out.push('\n');
            self.types(&mut out, q);
            doc(&mut out, q.text);
            match q.result {
                Ok(g) => {
                    let _ = writeln!(
                        out,
                        "export declare const {}: {RUNTIME_NS}.QueryOf<{}{}>;",
                        q.name,
                        self.query_types(q.name, g),
                        checks(&q.checks)
                    );
                }
                Err(e) => {
                    let _ = writeln!(
                        out,
                        "export declare const {}: {RUNTIME_NS}.BrokenQuery<{}>;",
                        q.name,
                        js_string(first_line(e))
                    );
                }
            }
        }
        out
    }

    /// The query's params and row interfaces (`any` for a query with an
    /// error).
    fn types(&self, out: &mut String, q: &SqlQuery) {
        let (params, row) = self.type_names.of(q.name);
        match q.result {
            Ok(g) => {
                interface(out, &params, &g.params);
                out.push('\n');
                interface(out, &row, &g.row);
                out.push('\n');
            }
            Err(_) => {
                let _ = writeln!(
                    out,
                    "export type {params} = any;\nexport type {row} = any;\n"
                );
            }
        }
    }

    /// `{ params: …Params; row: …Row; value: … }`.
    fn query_types(&self, name: &str, g: &Generated) -> String {
        let (params, row) = self.type_names.of(name);
        match &g.value {
            Some(v) => format!("{{ params: {params}; row: {row}; value: {v} }}"),
            None => format!("{{ params: {params}; row: {row} }}"),
        }
    }
}

/// `, [typedpg.Fits<T, U>, …]`: the check that each type `types` maps to
/// fits what its PG type is read as, compiled where the query uses it.
fn checks(checks: &[&TypeCheck]) -> String {
    if checks.is_empty() {
        return String::new();
    }
    let fits: Vec<String> = checks
        .iter()
        .map(|c| format!("{RUNTIME_NS}.Fits<{}, {}>", c.ts, c.fits))
        .collect();
    format!(", [{}]", fits.join(", "))
}

fn interface(out: &mut String, name: &str, members: &[String]) {
    if members.is_empty() {
        let _ = writeln!(out, "export interface {name} {{}}");
        return;
    }
    let _ = writeln!(out, "export interface {name} {{");
    for m in members {
        let _ = writeln!(out, "  {m};");
    }
    out.push_str("}\n");
}

/// The query's SQL as a doc comment, for the editor's hover.
fn doc(out: &mut String, sql: &str) {
    out.push_str("/**\n * ```sql\n");
    for line in sql.replace("*/", "*\\/").lines() {
        if line.is_empty() {
            out.push_str(" *\n");
        } else {
            let _ = writeln!(out, " * {line}");
        }
    }
    out.push_str(" * ```\n */\n");
}

/// An error's first line: the rest is the rendered snippet, which the CLI
/// prints.
fn first_line(e: &GenError) -> &str {
    e.message.lines().next().unwrap_or_default()
}

/// The `.sql` file at `source` as a generated module at `module` names it.
pub fn source_from(module: &Path, source: &Path) -> String {
    let dir = module.parent().unwrap_or(Path::new("/"));
    let rel = crate::project::relative_specifier(dir, source);
    rel.strip_prefix("./").map(str::to_owned).unwrap_or(rel)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ok(
        params: &[&str],
        row: &[&str],
        value: Option<&str>,
        overrides: &[&str],
    ) -> Result<Generated, GenError> {
        Ok(Generated {
            types: "{ … }".to_owned(),
            params: params.iter().map(|s| s.to_string()).collect(),
            row: row.iter().map(|s| s.to_string()).collect(),
            value: value.map(str::to_owned),
            overrides: overrides.iter().map(|s| s.to_string()).collect(),
            runtime: "{\"sql\":[\"x\"]}".to_owned(),
        })
    }

    fn names() -> TypeNames {
        TypeNames {
            params: "I{Name}Params".to_owned(),
            row: "I{Name}Result".to_owned(),
        }
    }

    #[test]
    fn typescript_module() {
        let a = ok(
            &["id: number"],
            &["prefs: UserPrefs | null"],
            Some("UserPrefs | null"),
            &["UserPrefs"],
        );
        let b = Err(GenError {
            message: "column \"x\" does not exist\n  ╭──".into(),
            offset: Some(7),
        });
        let check = TypeCheck {
            pg: "user_prefs".into(),
            ts: "UserPrefs".into(),
            fits: "typedpg.JsonValue".into(),
        };
        let imports = [
            ("./domains.ts".to_owned(), "Point".to_owned()),
            ("./domains.ts".to_owned(), "UserPrefs".to_owned()),
        ];
        let queries = [
            SqlQuery {
                name: "getPrefs",
                text: "SELECT prefs /* a */ FROM users WHERE id = $id",
                result: &a,
                checks: vec![&check],
            },
            SqlQuery {
                name: "bad",
                text: "SELECT x",
                result: &b,
                checks: vec![],
            },
        ];
        let names = names();
        let m = SqlModule {
            runtime: "@cubos/typedpg",
            source: "queries.sql".to_owned(),
            imports: &imports,
            queries: &queries,
            type_names: &names,
        };
        let files = m.files(Path::new("/p/queries.ts"), OutKind::TypeScript);
        let ts = &files[0].1;
        assert_eq!(
            ts,
            r#"// @generated by typedpg from the SQL file queries.sql. Do not edit:
// run `typedpg gen` after changing a query or a migration.
/* eslint-disable */
import { createBrokenQuery, createQuery } from "@cubos/typedpg";
import type * as typedpg from "@cubos/typedpg";
import type { UserPrefs } from "./domains.ts";

export interface IGetPrefsParams {
  id: number;
}

export interface IGetPrefsResult {
  prefs: UserPrefs | null;
}

/**
 * ```sql
 * SELECT prefs /* a *\/ FROM users WHERE id = $id
 * ```
 */
export const getPrefs = createQuery<{ params: IGetPrefsParams; row: IGetPrefsResult; value: UserPrefs | null }, [typedpg.Fits<UserPrefs, typedpg.JsonValue>]>(
  "SELECT prefs /* a */ FROM users WHERE id = $id",
  "{\"sql\":[\"x\"]}",
);

export type IBadParams = any;
export type IBadResult = any;

/**
 * ```sql
 * SELECT x
 * ```
 */
export const bad = createBrokenQuery("SELECT x", "column \"x\" does not exist");
"#
        );
        assert_eq!(
            generated_source(ts.lines().next().unwrap()),
            Some("queries.sql")
        );
        // A database's module is not one.
        assert_eq!(
            generated_source(
                "// @generated by typedpg from the queries in this project's sources. Do not edit:"
            ),
            None
        );

        let mapped = m.mapped();
        let names: Vec<&str> = mapped
            .exports
            .iter()
            .map(|&(at, i)| &mapped.text[at..at + queries[i].name.len()])
            .collect();
        assert_eq!(names, ["getPrefs", "bad"]);

        let dts = m.declaration_file();
        assert!(dts.contains("export declare const getPrefs: typedpg.QueryOf<{ params: IGetPrefsParams; row: IGetPrefsResult; value: UserPrefs | null }, [typedpg.Fits<UserPrefs, typedpg.JsonValue>]>;"), "{dts}");
        assert!(dts.contains("export declare const bad: typedpg.BrokenQuery<\"column \\\"x\\\" does not exist\">;"), "{dts}");

        let js = m.loader_module();
        assert!(js.starts_with("// compiled by typedpg from queries.sql\nimport { createBrokenQuery, createQuery } from \"@cubos/typedpg\";\n"), "{js}");
        assert!(
            !js.contains("interface") && !js.contains("IGetPrefs"),
            "{js}"
        );

        let cjs = m.files(Path::new("/p/queries.cjs"), OutKind::CommonJs);
        assert_eq!(cjs[1].0, PathBuf::from("/p/queries.d.cts"));
        assert!(
            cjs[0].1.contains("exports.getPrefs = createQuery("),
            "{}",
            cjs[0].1
        );
    }
}
