"""Turn the release's bootstrap catalog (postgres.bki) into C tables of the
pg_type and pg_namespace rows, for the crate's syscache (csrc/pg/syscache.c).

Usage: gen_catalog.py <src/include/catalog/postgres.bki>  (writes C to stdout)
"""
import re, sys
bki = open(sys.argv[1]).read().split('\n')
def table(name):
    cols, rows, i = [], [], 0
    while not bki[i].startswith(f'create {name} '): i += 1
    i += 1
    while not bki[i].strip().startswith(')'):
        m = re.match(r'\s*(\w+) = (\S+)', bki[i])
        if m: cols.append(m.group(1))
        i += 1
    while not bki[i].startswith(f'close {name}'):
        if bki[i].startswith('insert ('):
            vals = re.findall(r"'[^']*'|\S+", bki[i][len('insert ('):].rsplit(')', 1)[0])
            rows.append(dict(zip(cols, vals)))
        i += 1
    return rows
# Symbols initdb substitutes into the BKI, as the C compiler knows them.
SYMBOLS = {'SIZEOF_POINTER': 'SIZEOF_VOID_P', 'ALIGNOF_POINTER': "(SIZEOF_VOID_P == 4 ? 'i' : 'd')",
           'FLOAT8PASSBYVAL': 'FLOAT8PASSBYVAL'}
def c(v, kind):
    if v in SYMBOLS: return SYMBOLS[v]
    if kind == 'name': return '{"%s"}' % v
    if kind == 'bool': return 'true' if v == 't' else 'false'
    if kind == 'char': return "'%s'" % (v.strip("'") or '\\0')
    return '0' if v == '-' else v
T = {'typname': 'name', 'typbyval': 'bool', 'typispreferred': 'bool', 'typisdefined': 'bool',
     'typnotnull': 'bool', 'typtype': 'char', 'typcategory': 'char', 'typdelim': 'char',
     'typalign': 'char', 'typstorage': 'char'}
fixed = ['oid','typname','typnamespace','typowner','typlen','typbyval','typtype','typcategory',
         'typispreferred','typisdefined','typdelim','typrelid','typsubscript','typelem','typarray',
         'typinput','typoutput','typreceive','typsend','typmodin','typmodout','typanalyze',
         'typalign','typstorage','typnotnull','typbasetype','typtypmod','typndims','typcollation']
print('/* @generated by gen_catalog.py from postgres.bki. */')
print('#include "postgres.h"\n#include "catalog/pg_type.h"\n#include "catalog/pg_namespace.h"\n')
types = table('pg_type')
print('const FormData_pg_type typedpg_builtin_types[] = {')
for r in types:
    print('\t{' + ', '.join(f'.{k} = {c(r[k], T.get(k, "num"))}' for k in fixed) + '},')
print('};\nconst int typedpg_builtin_ntypes = %d;\n' % len(types))
ns = table('pg_namespace')
print('const FormData_pg_namespace typedpg_builtin_namespaces[] = {')
for r in ns:
    print('\t{.oid = %s, .nspname = {"%s"}, .nspowner = %s},' % (r['oid'], r['nspname'], r['nspowner']))
print('};\nconst int typedpg_builtin_nnamespaces = %d;' % len(ns))
