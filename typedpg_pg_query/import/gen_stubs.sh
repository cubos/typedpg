#!/bin/sh
# Generate postgres/typedpg/stubs_functions.c and stubs_variables.c: the
# symbols the imported PostgreSQL sources and the hand-written code under
# csrc/ reference but nothing in the crate defines.  A function stub raises an
# ERROR if reached; a variable stub is zeroed (csrc/pg/vars.c sets the ones
# that need a real value).
#
# Run from import.sh after builtin_catalog.c exists.  Adding a file under
# csrc/ only narrows the list: whatever it defines counts as defined.
set -eu

here=$(cd "$(dirname "$0")" && pwd)
crate=$(cd "$here/.." && pwd)
pg=$crate/postgres
out=$pg/typedpg

[ -f "$out/builtin_catalog.c" ] ||
	{ echo "gen_stubs.sh: $out/builtin_catalog.c missing; run import.sh" >&2; exit 1; }

LC_ALL=C
export LC_ALL

work=$(mktemp -d "${TMPDIR:-/tmp}/typedpg-stubs.XXXXXX")
trap 'rm -rf "$work"' EXIT HUP INT TERM

CF="-std=gnu11 -D_GNU_SOURCE -fno-strict-aliasing -fwrapv -fPIC -w
	-I$pg/include -I$pg/src/backend/parser -I$pg/src/pl/plpgsql/src -I$crate/csrc"

rm -f "$out/stubs_functions.c" "$out/stubs_variables.c"

# --- compile everything the crate will compile -----------------------------

{
	while IFS= read -r f; do
		[ -n "$f" ] && printf '%s\n' "$pg/$f"
	done <"$here/FILES"
	find "$crate/csrc" -type f -name '*.c' | sort
	find "$out" -type f -name '*.c' | sort
} >"$work/sources"

while IFS= read -r f; do
	obj=$(printf '%s' "${f#"$crate"/}" | tr '/' '_')
	# shellcheck disable=SC2086 # CF is a flag list
	gcc $CF -c "$f" -o "$work/$obj.o"
done <"$work/sources"

# --- symbols referenced but defined nowhere --------------------------------

nm -g --defined-only "$work"/*.o | awk 'NF == 3 { print $3 }' | sort -u >"$work/defined"
# Symbols the crate's Rust side defines (src/stack.rs), which the C compiler
# cannot see.
printf '%s\n' typedpg_remaining_stack >>"$work/defined"
sort -u -o "$work/defined" "$work/defined"
nm -u "$work"/*.o | awk '{ print $NF }' | grep -v ':' | sort -u |
	comm -23 - "$work/defined" >"$work/undef"

# A shared object that takes the address of each candidate: the linker names
# the ones libc/libm do not provide.
: >"$work/missing"
for s in $(cat "$work/undef"); do
	printf 'extern char %s; void *p_%s = &%s;\n' "$s" "$s" "$s"
done >"$work/probe.c"
# -lm: the math functions the imported sources use (floor, rint, ...) are
# libm's, not symbols the crate must stub.
if ! gcc -shared -o "$work/probe.so" "$work/probe.c" -Wl,--no-undefined -lm -w 2>"$work/err"; then
	sed -nE "s/.*undefined reference to [\`']([^']*)'.*/\1/p" "$work/err" |
		sort -u >"$work/missing"
	[ -s "$work/missing" ] ||
		{ cat "$work/err" >&2; echo "gen_stubs.sh: probe link failed" >&2; exit 1; }
fi

# --- decide function or variable for each missing symbol -------------------

# Declarations of variables in the imported headers, in a stable order: a
# symbol declared `extern PGDLLIMPORT` is data, everything else is code.
find "$pg/include" -type f -name '*.h' | sort >"$work/headers"
# shellcheck disable=SC2046 # the header list has no spaces
grep -hE '^extern PGDLLIMPORT ' $(cat "$work/headers") >"$work/pgdllimport" || true

is_variable() {
	grep -qE "^extern PGDLLIMPORT [^(]*[ *]$1(\[[^]]*\])?;" "$work/pgdllimport"
}

hdr='/* @generated by gen_stubs.sh: what the imported sources reference but the crate does not carry. */'

{
	printf '%s\n' "$hdr"
	printf '%s\n' '/* Functions: reaching one raises an ERROR (a gap in the file selection). */'
	printf '%s\n' '#ifdef _MSC_VER' \
		'extern __declspec(noreturn) void typedpg_unavailable(const char *name);' \
		'#else' \
		'extern void typedpg_unavailable(const char *name) __attribute__((noreturn));' \
		'#endif'
	while IFS= read -r s; do
		is_variable "$s" ||
			printf 'void %s(void) { typedpg_unavailable("%s"); }\n' "$s" "$s"
	done <"$work/missing"
} >"$out/stubs_functions.c"

{
	printf '%s\n' "$hdr"
	printf '%s\n' '/* Variables, zeroed (csrc/pg/vars.c sets the ones that need a value). */'
	for h in postgres.h miscadmin.h catalog/objectaccess.h utils/guc.h access/xact.h \
		storage/sinval.h access/parallel.h executor/spi.h utils/resowner.h; do
		printf '#include "%s"\n' "$h"
	done
	while IFS= read -r s; do
		grep -E "^extern PGDLLIMPORT [^(]*[ *]$s(\[[^]]*\])?;" "$work/pgdllimport" |
			head -1 | sed 's/^extern PGDLLIMPORT //'
	done <"$work/missing"
} >"$out/stubs_variables.c"

printf 'gen_stubs.sh: %s missing symbols\n' "$(wc -l <"$work/missing")" >&2
