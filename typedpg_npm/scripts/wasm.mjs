#!/usr/bin/env node
// Build `typedpg_wasm` for WebAssembly and embed the module in
// src/wasm.generated.ts, which the runtime imports as a base64 string: that
// is what lets `@cubos/typedpg` ship one file (and needs no bundler rule for
// `.wasm` assets), and the module is compiled lazily on first use (core.ts).
//
//   node scripts/wasm.mjs
//
// Needs Rust with the wasm32 target: `rustup target add wasm32-unknown-unknown`.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const pkgDir = dirname(dirname(fileURLToPath(import.meta.url)));
const root = dirname(pkgDir);

execFileSync(
  "cargo",
  ["build", "-p", "typedpg_wasm", "--target", "wasm32-unknown-unknown", "--profile", "wasm"],
  { cwd: root, stdio: "inherit" },
);

const targetDir = process.env.CARGO_TARGET_DIR
  ? resolve(root, process.env.CARGO_TARGET_DIR)
  : join(root, "target");
const wasm = readFileSync(
  join(targetDir, "wasm32-unknown-unknown", "wasm", "typedpg_wasm.wasm"),
);
const out = join(pkgDir, "src", "wasm.generated.ts");
writeFileSync(
  out,
  `// Generated by scripts/wasm.mjs — do not edit.\n\n` +
    `// Typed as \`string\`, not a literal: the declaration would otherwise\n` +
    `// repeat the whole module in the .d.ts.\n` +
    `export const WASM_MODULE_BASE64: string =\n  "${wasm.toString("base64")}";\n`,
);
console.log(`typedpg: embedded ${wasm.length} bytes of typedpg_wasm in src/wasm.generated.ts`);
