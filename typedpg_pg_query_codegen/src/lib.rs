//! Code generation for `typedpg_pg_query`.
//!
//! Two entry points produce the crate's generated sources:
//!
//! - [`generate`] derives them from libpg_query's `pg_query.proto` (the
//!   submodule's own description of PostgreSQL's AST), through
//!   `prost-build` and `protox`;
//! - [`generate_from_headers`] derives them straight from PostgreSQL's
//!   headers, with no `.proto` and no `prost` in the result — this is how the
//!   crate moves off libpg_query.
//!
//! Both produce:
//!
//! - `src/protobuf.rs`: the AST types (the name is historical: the types are
//!   plain Rust records now);
//! - `src/node.rs`: the `NodeRef` / `NodeMut` views over the `Node` oneof and
//!   the per-message child walkers behind `nodes()` / `nodes_mut()`;
//! - `src/equal.rs`: PostgreSQL's `equal()` over the messages — every field
//!   compared except the ones `equalfuncs.c` skips (parse locations and
//!   `equal_ignore` fields) — and the matching key, a string over the same
//!   fields.
//!
//! [`generate_from_headers`] also emits `src/convert.rs`, the conversion of
//! the C raw parse tree into those types (there is no C tree to convert from
//! in the `.proto` path).
//!
//! The walkers and the equality impls are shared: each entry point first
//! builds the same intermediate [`Model`] (messages, fields, the `Node`
//! variants), and the walker/equality generators work on that.

use std::collections::{HashMap, HashSet};
use std::fmt::Write;
use std::path::{Path, PathBuf};

use heck::{ToSnakeCase, ToUpperCamelCase};
use prost_types::field_descriptor_proto::{Label, Type};
use prost_types::{DescriptorProto, FileDescriptorSet};

pub mod ast;
pub mod convert;
pub mod schema;

/// The `typedpg_pg_query` crate directory, next to this one.
pub fn crate_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../typedpg_pg_query")
}

/// The generated files of the crate at `crate_dir`, as `(path, content)`,
/// derived from libpg_query's `pg_query.proto`.
pub fn generate(crate_dir: &Path) -> Vec<(PathBuf, String)> {
    let proto_dir = crate_dir.join("libpg_query/protobuf");
    let fds = protox::compile(["pg_query.proto"], [&proto_dir])
        .unwrap_or_else(|e| panic!("compiling {}/pg_query.proto: {e}", proto_dir.display()));
    let ignored = equal_ignored(&crate_dir.join("libpg_query/src/postgres/include/nodes"));
    let model = Model::from_fds(&fds);
    vec![
        (
            crate_dir.join("src/protobuf.rs"),
            rustfmt(&message_types(&fds)),
        ),
        (
            crate_dir.join("src/node.rs"),
            rustfmt(&walkers(&model, HEADER)),
        ),
        (
            crate_dir.join("src/equal.rs"),
            rustfmt(&equality(&model, &ignored, HEADER)),
        ),
    ]
}

/// The generated files of the crate, derived from PostgreSQL's headers:
/// `include_dir` is the directory configure's headers were installed to
/// (PostgreSQL's `src/include`, after `make generated-headers`) and `gram_h`
/// the `gram.h` Bison produced for the grammar.
///
/// The returned paths are relative to the `typedpg_pg_query` crate:
/// `src/protobuf.rs`, `src/node.rs`, `src/equal.rs` and `src/convert.rs`.
pub fn generate_from_headers(include_dir: &Path, gram_h: &Path) -> Vec<(PathBuf, String)> {
    let parsed = schema::Schema::parse(include_dir, gram_h);
    let program = ast::Program::from_schema(&parsed);
    let ignored = equal_ignored(&include_dir.join("nodes"));
    vec![
        (PathBuf::from("src/protobuf.rs"), rustfmt(&program.emit())),
        (
            PathBuf::from("src/node.rs"),
            rustfmt(&walkers(&program.model, HEADER_FROM_HEADERS)),
        ),
        (
            PathBuf::from("src/equal.rs"),
            rustfmt(&equality(&program.model, &ignored, HEADER_FROM_HEADERS)),
        ),
        (
            PathBuf::from("src/convert.rs"),
            rustfmt(&convert::generate(&parsed, &program)),
        ),
    ]
}

const HEADER: &str = "// @generated by typedpg_pg_query_codegen from libpg_query's pg_query.proto.\n\
                      // Do not edit; run `cargo run -p typedpg_pg_query_codegen`.\n\n";

pub(crate) const HEADER_FROM_HEADERS: &str = "// @generated by typedpg_pg_query_codegen from PostgreSQL's headers.\n\
                                   // Do not edit; run `cargo run -p typedpg_pg_query_codegen`.\n\n";

/// `prost-build`'s output for the `.proto`.
fn message_types(fds: &FileDescriptorSet) -> String {
    let out = std::env::temp_dir().join(format!("typedpg_pg_query_codegen_{}", std::process::id()));
    std::fs::create_dir_all(&out).expect("creating a temporary output directory");
    prost_build::Config::new()
        .out_dir(&out)
        .compile_fds(fds.clone())
        .expect("generating the protobuf types");
    let generated = std::fs::read_to_string(out.join("pg_query.rs")).expect("reading prost output");
    let _ = std::fs::remove_dir_all(&out);
    format!("{HEADER}{generated}")
}

/// Pipe `code` through `rustfmt`, so the output doesn't depend on how it was
/// assembled.
fn rustfmt(code: &str) -> String {
    use std::io::Write as _;
    let mut child = std::process::Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout", "--quiet"])
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .spawn()
        .expect("running rustfmt");
    child
        .stdin
        .take()
        .expect("rustfmt stdin")
        .write_all(code.as_bytes())
        .expect("writing to rustfmt");
    let output = child.wait_with_output().expect("waiting for rustfmt");
    assert!(
        output.status.success(),
        "rustfmt failed on the generated code"
    );
    String::from_utf8(output.stdout).expect("rustfmt output is UTF-8")
}

/// The Rust name `prost-build` gives a message (`A_Const` → `AConst`).
fn type_ident(proto_type_name: &str) -> String {
    proto_type_name
        .trim_start_matches(".pg_query.")
        .to_upper_camel_case()
}

/// The Rust name `prost-build` gives a field (keywords become raw
/// identifiers, as in `prost_build::ident::to_snake`).
fn field_ident(name: &str) -> String {
    let snake = name.to_snake_case();
    match snake.as_str() {
        "self" | "super" | "extern" | "crate" => format!("{snake}_"),
        "as" | "break" | "const" | "continue" | "else" | "enum" | "false" | "fn" | "for" | "if"
        | "impl" | "in" | "let" | "loop" | "match" | "mod" | "move" | "mut" | "pub" | "ref"
        | "return" | "static" | "struct" | "trait" | "true" | "type" | "unsafe" | "use"
        | "where" | "while" | "dyn" | "abstract" | "become" | "box" | "do" | "final" | "macro"
        | "override" | "priv" | "typeof" | "unsized" | "virtual" | "yield" | "async" | "await"
        | "try" | "gen" => format!("r#{snake}"),
        _ => snake,
    }
}

/// One way a message is reached from a field.
#[derive(Debug, Clone)]
pub(crate) enum Target {
    /// A `Node`: yield what it wraps.
    Node,
    /// A message that is a `Node` variant: yield it as that variant.
    Variant(String, String),
    /// Any other message: walk it without yielding.
    Plain(String),
}

/// The scalar shape of a field, as far as the generated Rust is concerned.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum FieldType {
    Bool,
    I32,
    I64,
    U32,
    U64,
    F32,
    F64,
    String,
    /// A `#[repr(i32)]` enum, stored as `i32`.
    Enum(String),
    /// Another message, by Rust type name.
    Message(String),
    /// A protobuf map (the summary API's `aliases`).
    Map,
}

/// One field of a [`Message`].
#[derive(Debug, Clone)]
pub(crate) struct Field {
    /// The field's proto name (`base_stmt`), from which Rust uses
    /// [`Field::rust`] and the oneof variant its upper-camel-case form.
    pub proto: String,
    /// PostgreSQL's field name (`base`), which `equal()`'s ignore list and
    /// the `location` lookup use.
    pub json: String,
    pub rust: String,
    pub ty: FieldType,
    pub repeated: bool,
    pub boxed: bool,
    /// Index into [`Message::oneofs`] when the field belongs to a oneof.
    pub oneof: Option<usize>,
    /// Set by [`Model::resolve_targets`].
    pub target: Option<Target>,
}

/// A oneof declaration (`Node.node`, `A_Const.val`).
#[derive(Debug, Clone)]
pub(crate) struct Oneof {
    /// The oneof's proto name (`node`).
    pub proto: String,
    /// The Rust struct field holding it (`node`).
    pub rust: String,
    /// The Rust enum's name (`Node`).
    pub enum_rust: String,
    /// Indices into [`Message::fields`].
    pub fields: Vec<usize>,
}

/// A message, as the walkers and equality see it.
#[derive(Debug, Clone)]
pub(crate) struct Message {
    /// The proto name (`A_Const`), which equality's ignore list keys on.
    pub name: String,
    pub rust: String,
    pub fields: Vec<Field>,
    pub oneofs: Vec<Oneof>,
    /// Nested messages (the summary API's), emitted but not walked.
    pub nested: Vec<Message>,
    /// Whether the proto message declares nested messages; equality skips
    /// those (no AST ever reaches them).
    pub has_nested: bool,
}

/// The intermediate model both entry points produce.
#[derive(Debug)]
pub struct Model {
    pub(crate) messages: Vec<Message>,
    /// `(variant, Rust message type)` in `Node` oneof declaration order.
    pub(crate) variants: Vec<(String, String)>,
    /// Rust message type → its `Node` variant.
    pub(crate) variant_of: HashMap<String, String>,
}

impl Model {
    /// The model of a `FileDescriptorSet` (libpg_query's `.proto`).
    fn from_fds(fds: &FileDescriptorSet) -> Model {
        let file = fds
            .file
            .iter()
            .find(|f| f.name() == "pg_query.proto")
            .expect("pg_query.proto in the descriptor set");
        let messages: Vec<Message> = file.message_type.iter().map(message_from_fds).collect();
        let mut model = Model {
            messages,
            variants: Vec::new(),
            variant_of: HashMap::new(),
        };
        // `Node`'s oneof names the variants.
        let node = model
            .messages
            .iter()
            .find(|m| m.name == "Node")
            .expect("message Node");
        model.variants = node
            .fields
            .iter()
            .map(|f| (f.proto.to_upper_camel_case(), message_type(f).to_string()))
            .collect();
        model.resolve_targets();
        model
    }

    pub(crate) fn resolve_targets(&mut self) {
        let mut variant_of = HashMap::new();
        for (variant, ty) in &self.variants {
            assert!(
                variant_of.insert(ty.clone(), variant.clone()).is_none(),
                "message {ty} appears twice in the Node oneof"
            );
        }
        self.variant_of = variant_of.clone();
        let top_level: HashSet<String> = self.messages.iter().map(|m| m.rust.clone()).collect();
        for message in &mut self.messages {
            for field in &mut message.fields {
                field.target = match &field.ty {
                    FieldType::Message(ty) if ty == "Node" => Some(Target::Node),
                    FieldType::Message(ty) => {
                        if let Some(variant) = variant_of.get(ty) {
                            Some(Target::Variant(variant.clone(), ty.clone()))
                        } else if top_level.contains(ty) {
                            Some(Target::Plain(ty.clone()))
                        } else {
                            // A nested (summary) record: no AST node can sit
                            // below it.
                            None
                        }
                    }
                    _ => None,
                };
            }
        }
    }
}

fn message_type(field: &Field) -> &str {
    match &field.ty {
        FieldType::Message(ty) => ty,
        other => panic!("field {} is not a message: {other:?}", field.proto),
    }
}

fn message_from_fds(m: &DescriptorProto) -> Message {
    // Nested messages (the summary API's) must be plain records: no AST node
    // can sit below them, so the walkers don't visit their fields.
    for nested in &m.nested_type {
        assert!(
            nested.field.iter().all(|f| f.r#type() != Type::Message)
                && nested.nested_type.is_empty(),
            "nested message {}.{} holds messages; the walker generator doesn't \
             handle that",
            m.name(),
            nested.name()
        );
    }
    let mut fields = Vec::new();
    for f in &m.field {
        let ty = match f.r#type() {
            Type::Message => FieldType::Message(type_ident(f.type_name())),
            Type::Enum => FieldType::Enum(type_ident(f.type_name())),
            Type::String => FieldType::String,
            Type::Bool => FieldType::Bool,
            Type::Int32 | Type::Sint32 | Type::Sfixed32 => FieldType::I32,
            Type::Int64 | Type::Sint64 | Type::Sfixed64 => FieldType::I64,
            Type::Uint32 | Type::Fixed32 => FieldType::U32,
            Type::Uint64 | Type::Fixed64 => FieldType::U64,
            Type::Float => FieldType::F32,
            Type::Double => FieldType::F64,
            other => panic!("message {} field {} has type {other:?}", m.name(), f.name()),
        };
        fields.push(Field {
            proto: f.name().to_string(),
            json: f.json_name().to_string(),
            rust: field_ident(f.name()),
            ty,
            repeated: f.label() == Label::Repeated,
            boxed: false,
            oneof: f
                .oneof_index
                .filter(|_| !f.proto3_optional())
                .map(|i| i as usize),
            target: None,
        });
    }
    let oneofs = m
        .oneof_decl
        .iter()
        .enumerate()
        .filter_map(|(i, oneof)| {
            let members: Vec<usize> = fields
                .iter()
                .enumerate()
                .filter(|(_, f)| f.oneof == Some(i))
                .map(|(index, _)| index)
                .collect();
            if members.is_empty() {
                return None;
            }
            Some(Oneof {
                proto: oneof.name().to_string(),
                rust: field_ident(oneof.name()),
                enum_rust: oneof.name().to_upper_camel_case(),
                fields: members,
            })
        })
        .collect();
    Message {
        name: m.name().to_string(),
        rust: type_ident(&format!(".pg_query.{}", m.name())),
        fields,
        oneofs,
        nested: Vec::new(),
        has_nested: !m.nested_type.is_empty(),
    }
}

fn walk_fn(ty: &str, mutable: bool) -> String {
    format!(
        "walk_{}{}",
        if mutable { "mut_" } else { "" },
        ty.to_snake_case()
    )
}

/// Statements visiting one value `x` of the field's message type.
fn visit(target: &Target, mutable: bool) -> String {
    match (target, mutable) {
        (Target::Node, false) => "visit_node(x, out);".into(),
        (Target::Node, true) => "out.slot(x);".into(),
        (Target::Variant(variant, ty), false) => {
            format!("let x: &'a protobuf::{ty} = x; out(NodeRef::{variant}(x));")
        }
        (Target::Variant(variant, ty), true) => {
            format!("let x: &mut protobuf::{ty} = x; out.node(NodeMut::{variant}(x));")
        }
        (Target::Plain(ty), false) => {
            format!(
                "let x: &'a protobuf::{ty} = x; {}(x, out);",
                walk_fn(ty, false)
            )
        }
        (Target::Plain(ty), true) => format!(
            "let x: &mut protobuf::{ty} = x; unsafe {{ {}(x, out) }};",
            walk_fn(ty, true)
        ),
    }
}

fn walkers(model: &Model, header: &str) -> String {
    let mut s = String::from(header);
    s.push_str(
        "//! Views over the `Node` oneof and the child walkers behind\n\
         //! `nodes()` / `nodes_mut()`.\n\n\
         #![allow(clippy::all, dead_code, unused_variables)]\n\n\
         use crate::protobuf;\n\n",
    );

    // NodeRef / NodeMut.
    s.push_str(
        "/// A borrowed view of one AST node, by kind.\n\
         #[derive(Debug, Clone, Copy)]\npub enum NodeRef<'a> {\n",
    );
    for (variant, ty) in &model.variants {
        writeln!(s, "    {variant}(&'a protobuf::{ty}),").unwrap();
    }
    s.push_str(
        "}\n\n/// A raw mutable pointer to one AST node, by kind (see `nodes_mut`).\n\
         #[derive(Debug, Clone, Copy)]\npub enum NodeMut {\n",
    );
    for (variant, ty) in &model.variants {
        writeln!(s, "    {variant}(*mut protobuf::{ty}),").unwrap();
    }
    s.push_str("}\n\n");

    // Conversions from the oneof.
    s.push_str(
        "impl protobuf::node::Node {\n    /// This node as a [`NodeRef`].\n    \
         pub fn to_ref(&self) -> NodeRef<'_> {\n        match self {\n",
    );
    for (variant, ty) in &model.variants {
        writeln!(
            s,
            "            Self::{variant}(x) => {{ let x: &protobuf::{ty} = x; NodeRef::{variant}(x) }}"
        )
        .unwrap();
    }
    s.push_str(
        "        }\n    }\n\n    /// This node as a [`NodeMut`] pointer.\n    \
         pub fn to_mut(&mut self) -> NodeMut {\n        match self {\n",
    );
    for (variant, ty) in &model.variants {
        writeln!(
            s,
            "            Self::{variant}(x) => {{ let x: &mut protobuf::{ty} = x; NodeMut::{variant}(x) }}"
        )
        .unwrap();
    }
    s.push_str("        }\n    }\n}\n\n");

    // The node's own token location.
    s.push_str(
        "impl NodeRef<'_> {\n    /// The node's `location` (a byte offset into the SQL), for the kinds\n    \
         /// that have one; `None` for the others and for an unknown one (-1).\n    \
         pub fn location(self) -> Option<i32> {\n        match self {\n",
    );
    for (variant, ty) in &model.variants {
        let has_location = model
            .messages
            .iter()
            .find(|m| &m.rust == ty)
            .is_some_and(Message::has_i32_location);
        if has_location {
            writeln!(
                s,
                "            NodeRef::{variant}(m) => (m.location >= 0).then_some(m.location),"
            )
            .unwrap();
        }
    }
    s.push_str("            _ => None,\n        }\n    }\n}\n\n");

    // Dispatch.
    s.push_str(
        "/// Call `out` on every direct child node of `node`.\n\
         pub(crate) fn children<'a>(node: NodeRef<'a>, out: &mut dyn FnMut(NodeRef<'a>)) {\n    \
         match node {\n",
    );
    for (variant, ty) in &model.variants {
        writeln!(
            s,
            "        NodeRef::{variant}(m) => {}(m, out),",
            walk_fn(ty, false)
        )
        .unwrap();
    }
    s.push_str(
        "    }\n}\n\n\
         /// What the mutable walkers report: a `Node` field (`slot`) or a field\n\
         /// of one node kind's own type (`node`).\n\
         trait MutVisitor {\n    \
         fn slot(&mut self, n: &mut protobuf::Node);\n    \
         fn node(&mut self, n: NodeMut);\n}\n\n\
         /// Walk the fields of `node` holding nodes.\n///\n\
         /// # Safety\n/// `node` must point to a live node no one else accesses.\n\
         unsafe fn walk_mut(node: NodeMut, out: &mut dyn MutVisitor) {\n    \
         match node {\n",
    );
    for (variant, ty) in &model.variants {
        writeln!(
            s,
            "        NodeMut::{variant}(m) => unsafe {{ {}(m, out) }},",
            walk_fn(ty, true)
        )
        .unwrap();
    }
    s.push_str(
        "    }\n}\n\n\
         struct Children<'f>(&'f mut dyn FnMut(NodeMut));\n\n\
         impl MutVisitor for Children<'_> {\n    \
         fn slot(&mut self, n: &mut protobuf::Node) {\n        \
         if let Some(e) = &mut n.node { (self.0)(e.to_mut()); }\n    }\n    \
         fn node(&mut self, n: NodeMut) { (self.0)(n); }\n}\n\n\
         /// Call `out` on every direct child node of `node`.\n///\n\
         /// # Safety\n/// `node` must point to a live node no one else accesses.\n\
         pub(crate) unsafe fn children_mut(node: NodeMut, out: &mut dyn FnMut(NodeMut)) {\n    \
         unsafe { walk_mut(node, &mut Children(out)) }\n}\n\n\
         struct Slots<'f>(&'f mut dyn FnMut(&mut protobuf::Node));\n\n\
         impl MutVisitor for Slots<'_> {\n    \
         fn slot(&mut self, n: &mut protobuf::Node) { (self.0)(n); }\n    \
         fn node(&mut self, n: NodeMut) { unsafe { walk_mut(n, self) } }\n}\n\n\
         /// Call `out` on every `Node` field below `node` reached without\n\
         /// passing through another one: the places a child node can be\n\
         /// replaced by a node of another kind.\n///\n\
         /// # Safety\n/// `node` must point to a live node no one else accesses.\n\
         pub(crate) unsafe fn child_slots_mut(node: NodeMut, out: &mut dyn FnMut(&mut protobuf::Node)) {\n    \
         unsafe { walk_mut(node, &mut Slots(out)) }\n}\n\n\
         fn visit_node<'a>(n: &'a protobuf::Node, out: &mut dyn FnMut(NodeRef<'a>)) {\n    \
         if let Some(e) = &n.node { out(e.to_ref()); }\n}\n\n",
    );

    // One walker per message.
    for m in &model.messages {
        if m.name == "Node" {
            continue;
        }
        for mutable in [false, true] {
            let body = message_body(m, mutable);
            if mutable {
                writeln!(
                    s,
                    "unsafe fn {}(m: *mut protobuf::{}, out: &mut dyn MutVisitor) {{\n    \
                     let m = unsafe {{ &mut *m }};\n{body}}}\n",
                    walk_fn(&m.rust, true),
                    m.rust
                )
                .unwrap();
            } else {
                writeln!(
                    s,
                    "fn {}<'a>(m: &'a protobuf::{}, out: &mut dyn FnMut(NodeRef<'a>)) {{\n{body}}}\n",
                    walk_fn(&m.rust, false),
                    m.rust
                )
                .unwrap();
            }
        }
    }
    s
}

impl Message {
    fn has_i32_location(&self) -> bool {
        self.fields
            .iter()
            .any(|f| f.json == "location" && f.ty == FieldType::I32)
    }
}

/// The statements of one message's walker.
fn message_body(m: &Message, mutable: bool) -> String {
    let (amp, iter) = if mutable {
        ("&mut ", "&mut ")
    } else {
        ("&", "&")
    };
    let mut body = String::new();
    for field in &m.fields {
        if field.oneof.is_some() {
            continue;
        }
        let Some(target) = &field.target else {
            continue;
        };
        let name = &field.rust;
        let visit = visit(target, mutable);
        if field.repeated {
            writeln!(body, "    for x in {iter}m.{name} {{ {visit} }}").unwrap();
        } else {
            writeln!(body, "    if let Some(x) = {amp}m.{name} {{ {visit} }}").unwrap();
        }
    }
    for oneof in &m.oneofs {
        writeln!(body, "    match {amp}m.{} {{", oneof.rust).unwrap();
        for &index in &oneof.fields {
            let field = &m.fields[index];
            let target = field.target.as_ref().expect("a message oneof member");
            writeln!(
                body,
                "        Some(protobuf::{}::{}::{}(x)) => {{ {} }}",
                m.rust.to_snake_case(),
                oneof.enum_rust,
                field.proto.to_upper_camel_case(),
                visit(target, mutable)
            )
            .unwrap();
        }
        body.push_str("        _ => {}\n    }\n");
    }
    body
}

/// The `(struct, field)` pairs PostgreSQL's `equal()` doesn't compare: fields
/// of type `ParseLoc` (source positions) and fields marked `equal_ignore`, as
/// declared in `parsenodes.h` / `primnodes.h`. Field names are PostgreSQL's,
/// which the `.proto` keeps as each field's `json_name`.
fn equal_ignored(headers: &Path) -> HashSet<(String, String)> {
    let mut out = HashSet::new();
    for file in ["parsenodes.h", "primnodes.h"] {
        let path = headers.join(file);
        let text = std::fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("reading {}: {e}", path.display()));
        let text = strip_c_comments(&text);
        let mut rest = text.as_str();
        while let Some(i) = rest.find("typedef struct ") {
            rest = &rest[i + "typedef struct ".len()..];
            let name: String = rest
                .chars()
                .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
                .collect();
            let (Some(open), Some(close)) = (rest.find('{'), rest.find("\n}")) else {
                break;
            };
            if open > close {
                continue;
            }
            for decl in rest[open + 1..close].split(';') {
                let decl = decl.trim();
                let ignore =
                    decl.contains("equal_ignore") && !decl.contains("equal_ignore_if_zero");
                if !(decl.starts_with("ParseLoc") || ignore) {
                    continue;
                }
                // Drop `pg_node_attr(...)`; the field is then the last word.
                let bare = match decl.find("pg_node_attr") {
                    Some(k) => &decl[..k],
                    None => decl,
                };
                if let Some(field) = bare
                    .split(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
                    .rfind(|w| !w.is_empty())
                {
                    out.insert((name.clone(), field.to_string()));
                }
            }
            rest = &rest[close..];
        }
    }
    assert!(
        out.contains(&("A_Expr".into(), "location".into())),
        "no ParseLoc fields found in the PostgreSQL headers"
    );
    out
}

fn strip_c_comments(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(i) = rest.find("/*") {
        out.push_str(&rest[..i]);
        rest = match rest[i..].find("*/") {
            Some(j) => &rest[i + j + 2..],
            None => "",
        };
    }
    out.push_str(rest);
    out.lines()
        .map(|l| l.split("//").next().unwrap_or(""))
        .collect::<Vec<_>>()
        .join("\n")
}

const EQUAL_PRELUDE: &str = r#"//! PostgreSQL's `equal()` (equalfuncs.c) over the AST: two trees are equal
//! when every field is, except source locations and the fields PostgreSQL
//! marks `equal_ignore`.

#![allow(clippy::all, unused_variables)]

use crate::protobuf;

/// Structural equality of AST values, as PostgreSQL's `equal()`.
pub trait Equal {
    fn equal(&self, other: &Self) -> bool;

    /// Append the value's key: a string over the fields `equal()` compares,
    /// the same for two values exactly when they are `equal()` — what to
    /// hash or store in place of the value. Every key is self-delimiting
    /// (a scalar ends in `;`, a message is braced, a list bracketed), so a
    /// sequence of keys reads back one way.
    fn equal_key(&self, out: &mut String);
}

impl<T: Equal> Equal for Option<T> {
    fn equal(&self, other: &Self) -> bool {
        match (self, other) {
            (Some(a), Some(b)) => a.equal(b),
            (None, None) => true,
            _ => false,
        }
    }

    fn equal_key(&self, out: &mut String) {
        match self {
            Some(a) => {
                out.push('?');
                a.equal_key(out);
            }
            None => out.push('~'),
        }
    }
}

impl<T: Equal> Equal for Box<T> {
    fn equal(&self, other: &Self) -> bool {
        (**self).equal(other)
    }

    fn equal_key(&self, out: &mut String) {
        (**self).equal_key(out)
    }
}

impl<T: Equal> Equal for Vec<T> {
    fn equal(&self, other: &Self) -> bool {
        self.len() == other.len() && self.iter().zip(other).all(|(a, b)| a.equal(b))
    }

    fn equal_key(&self, out: &mut String) {
        out.push('[');
        for a in self {
            a.equal_key(out);
        }
        out.push(']');
    }
}

macro_rules! scalar {
    ($($t:ty),*) => {$(
        impl Equal for $t {
            fn equal(&self, other: &Self) -> bool {
                self == other
            }

            fn equal_key(&self, out: &mut String) {
                use std::fmt::Write;
                let _ = write!(out, "{self:?};");
            }
        }
    )*};
}

scalar!(bool, i32, i64, u32, u64, u8, f32, f64, String);

"#;

fn equality(model: &Model, ignored: &HashSet<(String, String)>, header: &str) -> String {
    let mut s = String::from(header);
    s.push_str(EQUAL_PRELUDE);
    for m in &model.messages {
        // The summary API's records aren't AST.
        if m.has_nested {
            continue;
        }
        let ty = &m.rust;
        let mut fields: Vec<String> = Vec::new();
        let mut oneofs_done = HashSet::new();
        for field in &m.fields {
            if let Some(i) = field.oneof {
                if oneofs_done.insert(i) {
                    fields.push(m.oneofs[i].rust.clone());
                }
                continue;
            }
            if ignored.contains(&(m.name.clone(), field.json.clone())) {
                continue;
            }
            fields.push(field.rust.clone());
        }
        let body = if fields.is_empty() {
            "true".to_string()
        } else {
            fields
                .iter()
                .map(|f| format!("self.{f}.equal(&other.{f})"))
                .collect::<Vec<_>>()
                .join(" && ")
        };
        let key: String = fields
            .iter()
            .map(|f| format!("        self.{f}.equal_key(out);\n"))
            .collect();
        writeln!(
            s,
            "impl Equal for protobuf::{ty} {{\n    fn equal(&self, other: &Self) -> bool {{\n        {body}\n    }}\n\n    fn equal_key(&self, out: &mut String) {{\n        out.push('{{');\n{key}        out.push('}}');\n    }}\n}}\n"
        )
        .unwrap();
        for oneof in &m.oneofs {
            let module = m.rust.to_snake_case();
            let enum_ty = &oneof.enum_rust;
            let mut arms = String::new();
            let mut key_arms = String::new();
            for &index in &oneof.fields {
                let v = m.fields[index].proto.to_upper_camel_case();
                writeln!(
                    arms,
                    "            (Self::{v}(a), Self::{v}(b)) => a.equal(b),"
                )
                .unwrap();
                writeln!(
                    key_arms,
                    "            Self::{v}(a) => {{\n                out.push_str(\"{v}(\");\n                a.equal_key(out);\n                out.push(')');\n            }}"
                )
                .unwrap();
            }
            writeln!(
                s,
                "impl Equal for protobuf::{module}::{enum_ty} {{\n    fn equal(&self, other: &Self) -> bool {{\n        #[allow(unreachable_patterns)]\n        match (self, other) {{\n{arms}            _ => false,\n        }}\n    }}\n\n    fn equal_key(&self, out: &mut String) {{\n        match self {{\n{key_arms}        }}\n    }}\n}}\n"
            )
            .unwrap();
        }
    }
    s
}
