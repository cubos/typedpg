//! `INSERT ... SELECT` whose SELECT yields a row on every execution: no
//! FROM nor WHERE, aggregates without GROUP BY, or a subquery or CTE
//! doing so.
//! Storing that row fails every execution when it fails — even where the
//! SELECT isn't pulled up, so that PREPARE succeeds and EXECUTE fails.

use crate::common::*;

fn setup() -> PgCatalog {
    let mut db = PgCatalog::new().unwrap();
    db.apply_sql(
        "CREATE TABLE p (a int NOT NULL, b int);
         CREATE TABLE s9 (a int2, b int);
         CREATE TABLE v2 (a varchar(2), b int);
         CREATE DOMAIN dnn AS int NOT NULL;
         CREATE TABLE d (a dnn, b int);
         CREATE TABLE pt (k int, v int) PARTITION BY LIST (k);
         CREATE TABLE pt1 PARTITION OF pt FOR VALUES IN (1);
         CREATE TABLE tr (a int NOT NULL, b int);
         CREATE FUNCTION fill() RETURNS trigger LANGUAGE plpgsql
             AS $$BEGIN NEW.a := 1; RETURN NEW; END$$;
         CREATE TRIGGER t BEFORE INSERT ON tr FOR EACH ROW EXECUTE FUNCTION fill();
         CREATE TABLE idt (a int2 GENERATED BY DEFAULT AS IDENTITY NOT NULL, b int);
         CREATE TABLE ru (a int2 NOT NULL, b int);
         CREATE RULE ru_nothing AS ON INSERT TO ru DO INSTEAD NOTHING;
         CREATE TABLE ar (a int2[], b int);",
    )
    .unwrap();
    db
}

const NOT_NULL: &str = r#"null value in column "a" of relation "p" violates not-null constraint"#;

/// A NULL the row surely holds, stored into a NOT NULL column — given, or
/// left to a NULL default. A NULL stays NULL through strict casts, as in
/// a VALUES row.
#[test]
fn insert_select_storing_a_null_into_a_not_null_column_is_rejected() {
    let db = setup();
    for sql in [
        "INSERT INTO p (a) SELECT NULL",
        "INSERT INTO p (a) SELECT NULL::int8",
        "INSERT INTO p (a) SELECT NULL::text::int",
        "INSERT INTO p (a) SELECT NULL LIMIT 1",
        "INSERT INTO p (a) SELECT NULL OFFSET 0",
        "INSERT INTO p SELECT NULL, 1",
        "INSERT INTO p (a, b) SELECT NULL, count(*) FROM p",
        "INSERT INTO p (a, b) SELECT NULL, sum(b) FROM p",
        "INSERT INTO p (a, b) SELECT NULL, count(*) FROM p GROUP BY ()",
        "INSERT INTO p (a) SELECT x FROM (SELECT NULL::int AS x OFFSET 0) s",
        "INSERT INTO p (a) SELECT s.x FROM (SELECT NULL::int8 AS x, random() AS r) s",
        "INSERT INTO p (a) SELECT y FROM (SELECT NULL::int8 AS x OFFSET 0) s(y)",
        "INSERT INTO p (a) SELECT * FROM (SELECT NULL::int OFFSET 0) s",
        // A CTE yields its query's rows, inlined or not.
        "WITH c AS (SELECT NULL::int AS x) INSERT INTO p (a) SELECT x FROM c",
        "WITH c AS MATERIALIZED (SELECT NULL::int8 AS x) INSERT INTO p (a) SELECT c.x FROM c",
        "WITH c AS (SELECT NULL::int AS x), e AS (SELECT x FROM c) \
         INSERT INTO p (a) SELECT x FROM e",
        // The NOT NULL column left to its default.
        "INSERT INTO p (b) SELECT 1",
        "INSERT INTO p (b) SELECT count(*) FROM p WHERE b > 0",
    ] {
        assert_err_prefix!(db.analyze(sql), AnalyzeError::Invalid(_), NOT_NULL);
    }
    // A NOT NULL domain fails as the row is built.
    for sql in [
        "INSERT INTO d (b) SELECT count(*) FROM d",
        "INSERT INTO d (a) SELECT x FROM (SELECT NULL::int AS x OFFSET 0) s",
    ] {
        assert_err_prefix!(
            db.analyze(sql),
            AnalyzeError::Invalid(_),
            "domain dnn does not allow null values"
        );
    }
    // No partition takes the row.
    for sql in [
        "INSERT INTO pt (k) SELECT x FROM (SELECT 2 AS x OFFSET 0) s",
        "INSERT INTO pt (k, v) SELECT 2, count(*) FROM pt",
    ] {
        assert_err_prefix!(
            db.analyze(sql),
            AnalyzeError::CheckViolation(_),
            r#"no partition of relation "pt" found for row"#
        );
    }
}

/// A constant the row surely holds, out of its column's range: the
/// executor converts it as it stores the row (none of these SELECTs is
/// pulled up and folded).
#[test]
fn insert_select_storing_a_constant_out_of_range_is_rejected() {
    let db = setup();
    for sql in [
        "INSERT INTO s9 (a, b) SELECT 40000, count(*) FROM s9",
        "INSERT INTO s9 (a) SELECT x FROM (SELECT 40000 AS x OFFSET 0) s",
        "INSERT INTO s9 (a) SELECT x FROM (SELECT 40000 AS x, random() AS r) s",
        "INSERT INTO s9 (a) SELECT x FROM (SELECT 40000 AS x, count(*) FROM s9) s",
        "INSERT INTO s9 (a) SELECT 40000::int8 FROM (SELECT count(*) FROM s9) s",
        "INSERT INTO s9 (b, a) SELECT max(b), -40000 FROM s9",
        "INSERT INTO s9 (a, b) SELECT 40000, count(*) FROM s9 GROUP BY ()",
        "WITH c AS MATERIALIZED (SELECT 40000 AS x) INSERT INTO s9 (a) SELECT x FROM c",
        "WITH c(y, z) AS (SELECT count(*), 40000 FROM s9) INSERT INTO s9 (a) SELECT z FROM c",
        "WITH c(y, z) AS (SELECT count(*), 40000 FROM s9) \
         INSERT INTO s9 (a) SELECT w FROM c AS d(v, w)",
    ] {
        assert_err_prefix!(
            db.analyze(sql),
            AnalyzeError::NumericValueOutOfRange(_),
            "smallint out of range"
        );
    }
    for sql in [
        "INSERT INTO v2 (a, b) SELECT 'abc'::text, count(*) FROM v2",
        "INSERT INTO v2 (a) SELECT x FROM (SELECT 'abc'::text AS x OFFSET 0) s",
    ] {
        assert_err_prefix!(
            db.analyze(sql),
            AnalyzeError::Invalid(_),
            "value too long for type character varying(2)"
        );
    }
}

/// Neighbours PG accepts: the SELECT may yield no row (WHERE, LIMIT 0,
/// OFFSET, a set-returning function, GROUP BY, HAVING, a FROM table), the
/// value isn't stored (OVERRIDING USER VALUE, a DO INSTEAD rule, an array
/// element), a BEFORE ROW trigger may replace the NULL, or the statement
/// isn't run (plain EXPLAIN).
#[test]
fn insert_select_whose_row_may_not_fail_is_accepted() {
    let db = setup();
    for sql in [
        "INSERT INTO p (a) SELECT NULL WHERE false",
        "INSERT INTO p (a) SELECT NULL LIMIT 0",
        "INSERT INTO p (a) SELECT NULL OFFSET 1",
        "INSERT INTO p (a, b) SELECT NULL, generate_series(1, 0)",
        "INSERT INTO p (a, b) SELECT NULL, count(*) FROM p GROUP BY b",
        "INSERT INTO p (a, b) SELECT NULL, count(*) FROM p HAVING count(*) > 0",
        "INSERT INTO p (a) SELECT NULL FROM p",
        "INSERT INTO p (a) SELECT x FROM (SELECT NULL::int AS x OFFSET 0) s WHERE x IS NOT NULL",
        "INSERT INTO p (a) SELECT x FROM (SELECT NULL::int AS x FROM p) s",
        "INSERT INTO p (a) SELECT x FROM (SELECT NULL::int AS x OFFSET 1) s",
        "INSERT INTO p (a) SELECT x FROM (SELECT NULL::int AS x, generate_series(1, 0) AS g) s",
        "INSERT INTO p (a) SELECT 1 FROM (SELECT NULL::int AS x OFFSET 0) s",
        "INSERT INTO s9 (a) SELECT 40000 OFFSET 1",
        "WITH c AS (SELECT NULL::int AS x FROM p) INSERT INTO p (a) SELECT x FROM c",
        "WITH c AS MATERIALIZED (SELECT NULL::int AS x LIMIT 0) INSERT INTO p (a) SELECT x FROM c",
        "WITH c AS (SELECT NULL::int AS x) INSERT INTO p (a) SELECT x FROM c WHERE x > 0",
        "WITH c AS MATERIALIZED (SELECT 40000 AS x) INSERT INTO s9 (a) SELECT 1 FROM c",
        "INSERT INTO s9 (a) SELECT x FROM (SELECT 40000 AS x OFFSET 0) s WHERE x < 1",
        "INSERT INTO s9 (a, b) SELECT 40000, count(*) FROM s9 HAVING count(*) > 5",
        "INSERT INTO tr (a) SELECT NULL",
        "INSERT INTO tr (a, b) SELECT NULL, count(*) FROM tr",
        "INSERT INTO idt (a, b) OVERRIDING USER VALUE SELECT 40000, count(*) FROM idt",
        "INSERT INTO idt (a, b) OVERRIDING USER VALUE SELECT NULL, count(*) FROM idt",
        "INSERT INTO ru (a, b) SELECT 40000, count(*) FROM ru",
        "INSERT INTO ru (a, b) SELECT NULL, count(*) FROM ru",
        "INSERT INTO ar (a[1], b) SELECT NULL, count(*) FROM ar",
        "EXPLAIN INSERT INTO p (a) SELECT NULL",
        "EXPLAIN INSERT INTO s9 (a, b) SELECT 40000, count(*) FROM s9",
    ] {
        if let Err(e) = db.analyze(sql) {
            panic!("{sql}: {e}");
        }
    }
}
